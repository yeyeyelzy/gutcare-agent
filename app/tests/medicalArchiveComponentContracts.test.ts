import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'

const workspace = readFileSync(new URL('../src/components/MedicalArchiveWorkspace.vue', import.meta.url), 'utf8')
const archivePage = readFileSync(new URL('../src/pages/records/health-archive/index.vue', import.meta.url), 'utf8')
const detailPage = readFileSync(new URL('../src/pages/records/medical-documents/detail.vue', import.meta.url), 'utf8')
const pickerAndroid = readFileSync(new URL('../uni_modules/gutcare-medical-file-picker/utssdk/app-android/index.uts', import.meta.url), 'utf8')
const pickerIos = readFileSync(new URL('../uni_modules/gutcare-medical-file-picker/utssdk/app-ios/index.uts', import.meta.url), 'utf8')
const pickerWeb = readFileSync(new URL('../uni_modules/gutcare-medical-file-picker/utssdk/web/index.uts', import.meta.url), 'utf8')
const pickerInterface = readFileSync(new URL('../uni_modules/gutcare-medical-file-picker/utssdk/interface.uts', import.meta.url), 'utf8')
const preview = readFileSync(new URL('../src/api/medicalDocumentPreview.ts', import.meta.url), 'utf8')

describe('F02a archive workspace and native file safety contracts', () => {
  it('uses authenticated list/detail routes and a fail-closed three-step upload without parsing candidates', () => {
    expect(archivePage).toContain("canRenderRoute('healthArchive', auth.state)")
    expect(archivePage).toContain("requireAuthentication('healthArchive')")
    expect(detailPage).toContain("canRenderRoute('medicalDocumentDetail', auth.state)")
    expect(detailPage).toContain("requireAuthentication('medicalDocumentDetail')")
    expect(workspace).toContain('medical-document-list-loading')
    expect(workspace).toContain('medical-document-empty')
    expect(workspace).toContain('medical-document-list-error')
    expect(workspace).toContain('medical-document-append-error')
    expect(workspace).toContain('medical-document-upload-error')
    const session = workspace.indexOf('await api.createUpload(')
    const gateway = workspace.indexOf('await api.upload(', session)
    const complete = workspace.indexOf('await api.completeUpload(', gateway)
    const create = workspace.indexOf('await api.create(', complete)
    expect(session).toBeGreaterThanOrEqual(0)
    expect(gateway).toBeGreaterThan(session)
    expect(complete).toBeGreaterThan(gateway)
    expect(create).toBeGreaterThan(complete)
    expect(workspace).toContain("error.status === 503")
    expect(workspace).toContain("processingMode === 'analyze'")
    expect(workspace).toContain("processingMode === 'store_only'")
    expect(workspace).toContain('uni.showModal({ title: \'删除医疗档案？\'')
    expect(workspace).toContain("item.file_status !== 'deleting'")
    expect(workspace).not.toContain('patient_id')
    expect(workspace).not.toMatch(/candidate(?:_id|\.source)/i)
  })

  it('uses native single-file providers and cache-only cleanup while unsupported web fails closed', () => {
    expect(pickerAndroid).toMatch(/Intent\.ACTION_OPEN_DOCUMENT/)
    expect(pickerAndroid).toMatch(/EXTRA_MIME_TYPES/)
    expect(pickerAndroid).toMatch(/getCacheDir\(\)/)
    expect(pickerAndroid).toMatch(/getCanonicalPath\(\)/)
    expect(pickerAndroid).toContain("fail('cancelled')")
    expect(pickerAndroid).toContain('destination.delete()')
    expect(pickerAndroid).toContain("throw new Error('too_large')")
    expect(pickerAndroid).not.toMatch(/READ_EXTERNAL_STORAGE|MANAGE_EXTERNAL_STORAGE|READ_MEDIA_IMAGES/)
    expect(pickerIos).toContain('UIDocumentPickerViewController')
    expect(pickerIos).toContain('startAccessingSecurityScopedResource')
    expect(pickerIos).toContain('allowsMultipleSelection = false')
    expect(pickerIos).toContain('SearchPathDirectory.cachesDirectory')
    expect(pickerIos).toContain("finishFailure('cancelled')")
    expect(pickerIos).toContain('removeItem(at = destination)')
    expect(pickerInterface).toContain("'cancelled' | 'unsupported_type' | 'too_large' | 'unavailable'")
    expect(pickerWeb).toMatch(/unavailable|不支持/i)
    expect(workspace.slice(0, workspace.indexOf('<script setup'))).not.toMatch(/download_url|upload_url|capability/i)
  })

  it('bounds iOS provider copies before cache use and removes partial files on overflow', () => {
    const metadata = pickerIos.indexOf('attributesOfItem(atPath = source.path)')
    const earlyReject = pickerIos.indexOf('if (sourceSize != null && sourceSize > max)')
    const boundedCopy = pickerIos.indexOf('size = copyBounded(source, destination, max)')
    expect(metadata).toBeGreaterThanOrEqual(0)
    expect(earlyReject).toBeGreaterThan(metadata)
    expect(boundedCopy).toBeGreaterThan(earlyReject)
    expect(pickerIos).not.toContain('copyItem(at = source, to = destination)')

    const bounded = pickerIos.slice(pickerIos.indexOf('function copyBounded'), pickerIos.indexOf('function copyToCache'))
    expect(bounded).toContain('const boundedLimit = max + 1')
    expect(bounded).toMatch(/while \(copied < boundedLimit\)/)
    expect(bounded).toContain('if (copied > max) throw new Error(\'too_large\')')
    expect(bounded).toContain('removePartial(destination)')
    expect(pickerIos).toContain('try { FileManager.default.removeItem(at = destination) } catch (_cleanup) {}')
  })

  it('consumes one-time preview grants in memory and never persists or logs capability URLs', () => {
    expect(preview).toContain("grant.download_url = ''")
    expect(preview).toContain("headers: { Authorization: `Bearer ${accessToken}` }")
    expect(preview).toContain('private readonly temporaryPaths')
    expect(preview).toContain('async clear()')
    expect(preview).not.toMatch(/console\.(log|info|warn|error)/)
    expect(preview).not.toMatch(/localStorage|uni\.setStorage|uni\.setStorageSync/)
    expect(workspace).toContain('onHide(() => {')
    expect(workspace).toContain('const authorized = computed(() => canRenderRoute(isDetail.value ? \'medicalDocumentDetail\' : \'healthArchive\', auth.state))')
    expect(workspace).toContain('data-testid="medical-archive-auth-gate"')
    expect(workspace).toContain('pageGeneration++')
    expect(workspace).toContain('if (!canRenderRoute(routeName, auth.state))')
    expect(workspace.indexOf('router?.requireAuthentication(routeName)')).toBeLessThan(workspace.indexOf('void loadDetail()'))
    expect(workspace).toContain('nativeMedicalFilePicker.cleanup(oldFile.path)')
  })
})
